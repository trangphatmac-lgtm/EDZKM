package com.zelix.klassmaster.web;

import com.zelix.klassmaster.web.Models.*;
import java.nio.file.*;
import java.util.*;

public final class BuildScripts {
  private static final Set<String> QUOTED =
      Set.of(
          "changeLogFileOut",
          "changeLogFileIn",
          "looseChangeLogFileIn",
          "collapsePackagesWithDefault",
          "newNamesPrefix",
          "newPackageNameFile",
          "newClassNameFile",
          "newMethodNameFile",
          "newFieldNameFile",
          "autoReflectionPackage",
          "obfuscateReferencesPackage",
          "methodParameterChangesPackage",
          "lastModifiedTime",
          "assumeRuntimeVersion",
          "autoReflectionHash");

  public static String quote(String s) {
    return "\""
        + s.replace("\\", "/").replace("\"", "\\\"").replace("\n", "\\n").replace("\r", "\\r")
        + "\"";
  }

  public static String path(ProjectConfig p, String s) {
    if (s.indexOf('*') >= 0 || s.indexOf('?') >= 0 || s.indexOf('!') >= 0)
      return new java.io.File(s).isAbsolute() ? s : p.directory + java.io.File.separator + s;
    Path v = Path.of(s);
    return (v.isAbsolute() ? v : Path.of(p.directory).resolve(v)).normalize().toString();
  }

  public static String generate(ProjectConfig p, String mode) {
    BuildConfig b = p.build;
    StringBuilder out = new StringBuilder("// Generated by EDZKM Workbench\n");
    if (!mode.equals("statements") && !b.classpath.isEmpty())
      out.append("classpath ")
          .append(String.join(" ", b.classpath.stream().map(x -> quote(path(p, x))).toList()))
          .append(";\n");
    if (!mode.equals("statements") && !b.inputs.isEmpty()) {
      out.append("open openNestedArchives=")
          .append(b.openNestedArchives)
          .append(" ")
          .append(String.join(" ", b.inputs.stream().map(x -> quote(path(p, x))).toList()))
          .append(String.join("", b.skipped.stream().map(x -> " -" + quote(path(p, x))).toList()))
          .append(String.join("", b.restored.stream().map(x -> " +" + quote(path(p, x))).toList()))
          .append(";\n\n");
    }
    if (mode.equals("open")) return out.toString();
    if (mode.equals("statements"))
      out.append(
          "resetTrimExclusions; resetExclusions; resetGroupings; resetFixedClasses;"
              + " resetRemoveMethodCalls; resetAccessedByReflection; resetIgnoreMissingReferences;"
              + " resetObfuscateFlowExclusions; resetLongEncryptionExclusions;"
              + " resetStringEncryptionExclusions; resetIntegerEncryptionExclusions;"
              + " resetObfuscateReferenceExclusions; resetObfuscateExceptionsExclusions;"
              + " resetMethodParameterChangesExclusions;"
              + " resetMethodParameterObfuscationExclusions;\n");
    if (b.trim) {
      appendRules(out, b.trimRules);
      out.append(statement("trim", b.trimOptions)).append("\n");
    }
    if (b.obfuscate) {
      appendRules(out, b.rules);
      Map<String, String> options = new LinkedHashMap<>(b.obfuscation);
      for (String k :
          List.of(
              "changeLogFileOut",
              "changeLogFileIn",
              "looseChangeLogFileIn",
              "newPackageNameFile",
              "newClassNameFile",
              "newMethodNameFile",
              "newFieldNameFile"))
        if (options.containsKey(k) && !options.get(k).isEmpty())
          options.put(k, path(p, options.get(k)));
      out.append(statement("obfuscate", options)).append("\n");
    }
    if (!mode.equals("transform") && !mode.equals("statements"))
      out.append("saveAll ")
          .append(parameters(b.saveOptions))
          .append(" ")
          .append(quote(path(p, b.output)))
          .append(";\n");
    return out.toString();
  }

  private static void appendRules(StringBuilder out, String text) {
    if (!text.isBlank()) {
      out.append(text.trim());
      if (!text.trim().endsWith(";")) out.append(';');
      out.append('\n');
    }
  }

  public static String statement(String name, Map<String, String> values) {
    return name + " " + parameters(values) + ";";
  }

  public static String parameters(Map<String, String> values) {
    StringBuilder out = new StringBuilder();
    values.forEach(
        (k, v) -> {
          if (!k.matches("[a-zA-Z][a-zA-Z0-9]*"))
            throw new IllegalArgumentException("Invalid option: " + k);
          if (!QUOTED.contains(k) && !v.matches("[a-zA-Z0-9_.+-]+"))
            throw new IllegalArgumentException("Invalid value for " + k);
          out.append("\n    ").append(k).append('=').append(QUOTED.contains(k) ? quote(v) : v);
        });
    return out.toString();
  }
}
